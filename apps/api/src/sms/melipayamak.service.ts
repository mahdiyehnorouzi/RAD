import {
  Injectable,
  InternalServerErrorException,
  Logger,
} from "@nestjs/common";
import { ConfigService } from "@nestjs/config";

const SEND_OTP_URL = "https://rest.payamak-panel.com/api/SendSMS/SendOtp";
const REQUEST_TIMEOUT_MS = 10_000;

/**
 * Payamak Panel's SendOtp success body is
 * `{"Value":"...","RetStatus":1,"StrRetStatus":"Ok"}`.
 * `Value` is a provider receipt only — never the OTP this service sent.
 * Anything else (non-JSON, another RetStatus, a StrRetStatus other than
 * "Ok") is a failed delivery.
 */
function deliveryStatus(payload: unknown): {
  accepted: boolean;
  retStatus: string;
} {
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) {
    return { accepted: false, retStatus: "missing" };
  }
  const record = payload as { RetStatus?: unknown; StrRetStatus?: unknown };
  const retStatus = record.RetStatus;
  const retLabel =
    typeof retStatus === "number" && Number.isInteger(retStatus)
      ? String(retStatus)
      : typeof retStatus === "string" && /^-?\d{1,6}$/.test(retStatus.trim())
        ? retStatus.trim()
        : "unrecognized";
  const strStatus =
    typeof record.StrRetStatus === "string" ? record.StrRetStatus.trim() : "";
  return {
    accepted: retLabel === "1" && strStatus.toLowerCase() === "ok",
    retStatus: retLabel,
  };
}

function configuredSetting(value: string | undefined) {
  const trimmed = value?.trim();
  return trimmed ? trimmed : undefined;
}

/**
 * Sends one OTP SMS via Payamak Panel's `SendOtp` REST API
 * (`POST` `application/x-www-form-urlencoded`: `username`, `password`,
 * `to`, `from`, `code`). The `code` is the OTP `OtpService` already
 * generated; this class never reads a code out of the provider response.
 *
 * Mirrors `MailService`'s isConfigured()/disabled-until-configured pattern:
 * missing credentials never crash the API, but every call fails loud and
 * coded until `MELIPAYAMAK_USERNAME`/`MELIPAYAMAK_PASSWORD`/
 * `MELIPAYAMAK_SENDER` are set (see `apps/api/.env.example`). Blank or
 * whitespace-only values count as unset.
 *
 * Never logs the OTP, the credentials, the recipient, or the request body.
 * A send is reported only after `RetStatus` 1 and `StrRetStatus` "Ok".
 */
@Injectable()
export class MelipayamakService {
  private readonly logger = new Logger(MelipayamakService.name);

  constructor(private readonly config: ConfigService) {}

  isConfigured() {
    return Boolean(
      configuredSetting(this.config.get<string>("MELIPAYAMAK_USERNAME")) &&
      configuredSetting(this.config.get<string>("MELIPAYAMAK_PASSWORD")) &&
      configuredSetting(this.config.get<string>("MELIPAYAMAK_SENDER")),
    );
  }

  /** Called once at boot (see `main.ts`), same as `MailService.logConfigurationStatus`. */
  logConfigurationStatus() {
    if (this.isConfigured()) {
      this.logger.log("Melipayamak is configured; SMS OTP is enabled.");
      return;
    }
    this.logger.warn(
      "Melipayamak is NOT configured (MELIPAYAMAK_USERNAME/PASSWORD/SENDER " +
        "missing). SMS OTP sign-in will fail until these are set.",
    );
  }

  /** `to`: an Iranian mobile number, digits only, e.g. "09121234567". `code`: the OTP generated by `OtpService`. */
  async sendOtp(to: string, code: string): Promise<void> {
    const username = configuredSetting(
      this.config.get<string>("MELIPAYAMAK_USERNAME"),
    );
    const password = configuredSetting(
      this.config.get<string>("MELIPAYAMAK_PASSWORD"),
    );
    const from = configuredSetting(
      this.config.get<string>("MELIPAYAMAK_SENDER"),
    );
    if (!username || !password || !from) {
      throw new InternalServerErrorException({
        message:
          "ارسال پیامک پیکربندی نشده است. MELIPAYAMAK_USERNAME، MELIPAYAMAK_PASSWORD و MELIPAYAMAK_SENDER را در apps/api/.env تنظیم کنید.",
        code: "melipayamak_not_configured",
      });
    }

    const body = new URLSearchParams({
      username,
      password,
      to,
      from,
      code,
    });

    let response: Response;
    try {
      response = await fetch(SEND_OTP_URL, {
        method: "POST",
        headers: { "content-type": "application/x-www-form-urlencoded" },
        body,
        signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      });
    } catch (error) {
      const reason = error instanceof Error ? error.name : "Error";
      this.logger.error(`Melipayamak SendOtp request failed: ${reason}`);
      throw new InternalServerErrorException(
        "ارسال پیامک ناموفق بود. دوباره تلاش کنید.",
      );
    }

    let payload: unknown;
    try {
      payload = JSON.parse((await response.text()).trim());
    } catch {
      payload = undefined;
    }
    const status = deliveryStatus(payload);
    // HTTP status and a short RetStatus are the delivery signal. `Value` is
    // ignored: it is not the OTP. A long RetStatus is not logged, so a body
    // that echoes the code cannot land in the log.
    if (!response.ok || !status.accepted) {
      const retStatus = /^-?\d{1,4}$/.test(status.retStatus)
        ? status.retStatus
        : "unrecognized";
      this.logger.warn(
        `Melipayamak SendOtp was not accepted (HTTP ${response.status}, RetStatus ${retStatus})`,
      );
      throw new InternalServerErrorException(
        "ارسال پیامک ناموفق بود. دوباره تلاش کنید.",
      );
    }
  }
}
